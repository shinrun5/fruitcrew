// every field but name is optional: the server leaves anything omitted as-is
type StorePatch = {
  name: string
  requiresOpenerSkill?: boolean
  pairNewWorkers?: boolean
  tracksClosingDuties?: boolean
  openTime?: string | null
  closeTime?: string | null
  nightStart?: string | null
  availabilityReminderDay?: DayOfWeek
  availabilityReminderTime?: string
  autoGenerateDay?: DayOfWeek
  autoGenerateTime?: string
  autoApproveTrades?: boolean
  tradeCutoffHours?: number
  timeClock?: TimeClockMode
}

// every half hour, "00:00".."23:30" — a plain <select> of these renders the
// same everywhere, unlike a native <input type="time">, which looks and
// behaves differently per browser/OS (and inconsistently blank/greyed-out
// until a value's actually picked)
const TIME_OPTIONS: string[] = Array.from({ length: 48 }, (_, i) => {
  const h = Math.floor(i / 2)
  const m = i % 2 === 0 ? '00' : '30'
  return `${String(h).padStart(2, '0')}:${m}`
})

export function Stores() {
  const t = useT()
  const confirm = useConfirm()
  const { user } = useAuth()
  const isOwner = user?.role === 'OWNER'
  const [stores, setStores] = useState<Store[]>([])
  const [links, setLinks] = useState<EmployeeStore[]>([])
  const [reqs, setReqs] = useState<ShiftRequirement[]>([])
  const [error, setError] = useState<string | null>(null)
  const [loading, setLoading] = useState(true)
  const [editing, setEditing] = useState<number | null>(null)
  const [showNeeds, setShowNeeds] = useState<number | null>(null)
  const [showHours, setShowHours] = useState<number | null>(null)
  const [showInvite, setShowInvite] = useState<number | null>(null)
  const [showResp, setShowResp] = useState<number | null>(null)
  const [showTiming, setShowTiming] = useState<number | null>(null)
  const [showTrades, setShowTrades] = useState<number | null>(null)
  const [showClock, setShowClock] = useState<number | null>(null)
  const [addingSectionFor, setAddingSectionFor] = useState<number | null>(null)
  const [org, setOrg] = useState<{
    id: number
    name: string
    payPeriodType: PayPeriodType
    payPeriodAnchor: string
    storeLimit: number | null
    managersSeePay: boolean
  } | null>(null)
  const [payBusy, setPayBusy] = useState(false)

  const [billing, setBilling] = useState<BillingSummary | null>(null)
  const [addOpen, setAddOpen] = useState(false)
  useEffect(() => {
    if (!isOwner) return
    api.getOrg().then(setOrg).catch(() => {})
    api.getBilling().then(setBilling).catch(() => {})
  }, [isOwner])

  // back from Stripe Checkout: the plan arrives a moment later (Stripe tells
  // the server by webhook), so check again for a little while
  useEffect(() => {
    if (!isOwner || new URLSearchParams(window.location.search).get('billing') !== 'done') return
    let tries = 0
    const id = window.setInterval(() => {
      tries++
      api
        .getBilling()
        .then((b) => {
          setBilling(b)
          if (b.state === 'active' || tries >= 10) window.clearInterval(id)
        })
        .catch(() => {})
    }, 3000)
    return () => window.clearInterval(id)
  }, [isOwner])
  const atStoreLimit =
    billing?.storeLimit != null && stores.filter((s) => s.parentStoreId === null).length >= billing.storeLimit

  const { refreshStores } = useStore()
  function refresh() {
    // the header's store picker too, so an added or deleted store shows up there
    void refreshStores()
    return Promise.all([api.getStores(), api.getEmployeeStores(), api.getShiftRequirements()])
      .then(([s, l, r]) => {
        setStores(s)
        setLinks(l)
        setReqs(r)
      })
      .catch((e) => setError(e instanceof Error ? e.message : t('stores.errLoad')))
  }

  useEffect(() => {
    refresh().finally(() => setLoading(false))
  }, [])

  const workerCount = (storeId: number) => links.filter((l) => l.storeId === storeId).length
  const reqCount = (storeId: number) => reqs.filter((r) => r.storeId === storeId).length
  const sectionsOf = (storeId: number) => stores.filter((s) => s.parentStoreId === storeId)

  /** Run a save; true if it worked. A form stays open when it didn't, so
   * nothing typed is lost and the error shows next to it. */
  async function act(fn: () => Promise<unknown>): Promise<boolean> {
    setError(null)
    try {
      await fn()
    } catch (e) {
      setError(e instanceof Error ? e.message : t('stores.errGeneric'))
      return false
    }
    setEditing(null)
    await refresh().catch(() => {})
    return true
  }

  async function addSection(parent: Store, name: string) {
    // first section under a store that already has its own shift requirements —
    // those requirements stay right where they are, but the store itself stops
    // being schedulable once it has sections, so make sure that's not a surprise
    if (
      sectionsOf(parent.id).length === 0 &&
      reqCount(parent.id) > 0 &&
      !(await confirm(t('stores.confirmFirstSection', { name: parent.name }), { tone: 'danger' }))
    ) {
      return
    }
    setError(null)
    try {
      await api.createStore({ name, requiresOpenerSkill: true, pairNewWorkers: false, parentStoreId: parent.id })
      setAddingSectionFor(null)
      await refresh()
    } catch (e) {
      setError(e instanceof Error ? e.message : t('stores.errGeneric'))
    }
  }

  const noStores = !loading && stores.length === 0
  return (
    <div className="mx-auto w-full max-w-2xl flex-1 p-4 pb-[calc(4rem+env(safe-area-inset-bottom))] sm:p-6">
      <h1 className="font-heading text-lg font-bold text-ink">{t('nav.mgr.stores')}</h1>
      {error && <p className="mt-2 font-body text-xs font-bold text-coral-dark">{error}</p>}

      {isOwner && org && (
        <>
          <SectionHeading title={t('settings.company')} />
          <div className="flex flex-col gap-2 rounded-2xl border-[2.5px] border-ink bg-paper p-3 shadow-[3px_3px_0_var(--color-ink)]">
            <OrgNameEditor org={org} onSaved={(o) => setOrg((prev) => prev && { ...prev, ...o })} />
            <PayCycleEditor org={org} onSaved={(o) => setOrg((prev) => prev && { ...prev, ...o })} />
            <Toggle
              on={org.managersSeePay}
              busy={payBusy}
              label={t('settings.managersSeePay')}
              hint={t('settings.managersSeePayHint')}
              onClick={async () => {
                setPayBusy(true)
                try {
                  const r = await api.setPayVisibility(!org.managersSeePay)
                  setOrg((prev) => prev && { ...prev, ...r })
                } catch (e) {
                  setError(e instanceof Error ? e.message : String(e))
                } finally {
                  setPayBusy(false)
                }
              }}
            />
          </div>
        </>
      )}

      <SectionHeading title={t('settings.locations')} hint={t('stores.subtitle')} />
      {isOwner &&
        billing &&
        // every store the plan pays for is in use (sections don't count) — the backend refuses too
        (atStoreLimit ? (
          <StoreLimitNote
            billing={billing}
            onAdded={(b) => {
              setBilling(b)
              setAddOpen(true)
            }}
          />
        ) : (
          <AddStore
            key={addOpen || noStores ? 'open' : 'closed'}
            // a brand-new business has nothing else to do here yet
            startOpen={addOpen || noStores}
            onAdd={async (patch) => {
              const ok = await act(() => api.createStore(patch))
              if (ok) setAddOpen(false)
              return ok
            }}
          />
        ))}

      {loading ? (
        <p className="mt-3 font-body text-sm text-muted-ink">{t('common.loading')}</p>
      ) : (
        <div className="flex flex-col gap-3">
          {stores
            .filter((s) => s.parentStoreId === null)
            .map((s) => (
              <div key={s.id} className="flex flex-col gap-2.5">
                {editing === s.id ? (
                  <EditStore
                    store={s}
                    hasSections={sectionsOf(s.id).length > 0}
                    onSave={(patch) => act(() => api.updateStore(s.id, patch))}
                    onCancel={() => setEditing(null)}
                  />
                ) : (
                  <StoreCard
                    store={s}
                    isOwner={isOwner}
                    hasSections={sectionsOf(s.id).length > 0}
                    workerCount={workerCount(s.id)}
                    reqCount={reqCount(s.id)}
                    showNeeds={showNeeds === s.id}
                    showHours={showHours === s.id}
                    showInvite={showInvite === s.id}
                    showResp={showResp === s.id}
                    onToggleNeeds={() => setShowNeeds((v) => (v === s.id ? null : s.id))}
                    onToggleHours={() => setShowHours((v) => (v === s.id ? null : s.id))}
                    onToggleInvite={() => setShowInvite((v) => (v === s.id ? null : s.id))}
                    onToggleResp={() => setShowResp((v) => (v === s.id ? null : s.id))}
                    showTiming={showTiming === s.id}
                    onToggleTiming={() => setShowTiming((v) => (v === s.id ? null : s.id))}
                    onSaveTiming={(patch) =>
                      void act(() => api.updateStore(s.id, patch)).then((ok) => ok && setShowTiming(null))
                    }
                    showTrades={showTrades === s.id}
                    onToggleTrades={() => setShowTrades((v) => (v === s.id ? null : s.id))}
                    onSaveTrades={(patch) =>
                      void act(() => api.updateStore(s.id, patch)).then((ok) => ok && setShowTrades(null))
                    }
                    showClock={showClock === s.id}
                    onToggleClock={() => setShowClock((v) => (v === s.id ? null : s.id))}
                    onSaveClock={(patch) =>
                      void act(() => api.updateStore(s.id, patch)).then((ok) => ok && setShowClock(null))
                    }
                    onEdit={() => setEditing(s.id)}
                    onDelete={() => {
                      void confirm(t('stores.confirmDelete', { name: s.name }), {
                        tone: 'danger',
                        confirmLabel: t('stores.delete'),
                      }).then((ok) => {
                        if (ok) void act(() => api.deleteStore(s.id))
                      })
                    }}
                    onRefresh={refresh}
                  />
                )}

                {sectionsOf(s.id).map((sec) => (
                  <div key={sec.id} className="ml-4 flex flex-col gap-2.5 border-l-2 border-ink/15 pl-3 sm:ml-6">
                    {editing === sec.id ? (
                      <EditStore
                        store={sec}
                        onSave={(patch) => act(() => api.updateStore(sec.id, patch))}
                        onCancel={() => setEditing(null)}
                      />
                    ) : (
                      <StoreCard
                        store={sec}
                        isSection
                        isOwner={isOwner}
                        workerCount={workerCount(sec.id)}
                        reqCount={reqCount(sec.id)}
                        showNeeds={showNeeds === sec.id}
                        showHours={showHours === sec.id}
                        showInvite={showInvite === sec.id}
                        showResp={showResp === sec.id}
                        onToggleNeeds={() => setShowNeeds((v) => (v === sec.id ? null : sec.id))}
                        onToggleHours={() => setShowHours((v) => (v === sec.id ? null : sec.id))}
                        onToggleInvite={() => setShowInvite((v) => (v === sec.id ? null : sec.id))}
                        onToggleResp={() => setShowResp((v) => (v === sec.id ? null : sec.id))}
                        onEdit={() => setEditing(sec.id)}
                        onDelete={() => {
                          void confirm(t('stores.confirmDelete', { name: sec.name }), {
                            tone: 'danger',
                            confirmLabel: t('stores.delete'),
                          }).then((ok) => {
                            if (ok) void act(() => api.deleteStore(sec.id))
                          })
                        }}
                        onRefresh={refresh}
                      />
                    )}
                  </div>
                ))}

                {/* any manager of this store can add a section to it, not just an
                    owner — the page's own store list is already scoped to
                    stores this account manages, so every card here qualifies */}
                {addingSectionFor === s.id ? (
                  <div className="ml-4 sm:ml-6">
                    <AddSection onAdd={(name) => void addSection(s, name)} onCancel={() => setAddingSectionFor(null)} />
                  </div>
                ) : (
                  <button
                    onClick={() => setAddingSectionFor(s.id)}
                    className="ml-4 self-start rounded-full border-2 border-dashed border-ink/40 px-2.5 py-0.5 font-heading text-[11px] font-bold text-muted-ink sm:ml-6"
                  >
                    {t('stores.addSection')}
                  </button>
                )}
              </div>
            ))}
        </div>
      )}

      {isOwner && !loading && stores.length > 0 && (
        <div className="mt-6">
          <ManagersSection stores={stores} />
        </div>
      )}

      {/* the plan comes last: locations are what a new owner is here to set up */}
      {isOwner && billing && (
        <>
          <SectionHeading title={t('billing.heading')} />
          <PlanPanel billing={billing} onChange={setBilling} />
        </>
      )}
    </div>
  )
}

function SectionHeading({ title, hint }: { title: string; hint?: string }) {
  return (
    <div className="mb-2 mt-6">
      <h2 className="font-body text-[11px] font-bold uppercase tracking-wide text-muted-ink">{title}</h2>
      {hint && <p className="font-body text-xs text-muted-ink">{hint}</p>}
    </div>
  )
}

function StoreCard({
  store: s,
  isSection = false,
  hasSections = false,
  isOwner,
  workerCount,
  reqCount,
  showNeeds,
  showHours,
  showInvite,
  showResp,
  showTiming = false,
  showTrades = false,
  onToggleTrades,
  onSaveTrades,
  showClock = false,
  onToggleClock,
  onSaveClock,
  onToggleNeeds,
  onToggleHours,
  onToggleInvite,
  onToggleResp,
  onToggleTiming,
  onSaveTiming,
  onEdit,
  onDelete,
  onRefresh,
}: {
  store: Store
  showTiming?: boolean
  onToggleTiming?: () => void
  onSaveTiming?: (patch: StorePatch) => void
  showTrades?: boolean
  onToggleTrades?: () => void
  onSaveTrades?: (patch: StorePatch) => void
  showClock?: boolean
  onToggleClock?: () => void
  onSaveClock?: (patch: StorePatch) => void
  isSection?: boolean
  /** true once this store has its own sections — it's no longer itself
   * schedulable, so its own "shift needs" would never actually be used */
  hasSections?: boolean
  isOwner: boolean
  workerCount: number
  reqCount: number
  showNeeds: boolean
  showHours: boolean
  showInvite: boolean
  showResp: boolean
  onToggleNeeds: () => void
  onToggleHours: () => void
  onToggleInvite: () => void
  onToggleResp: () => void
  onEdit: () => void
  onDelete: () => void
  onRefresh: () => void
}) {
  const t = useT()
  return (
    <div className="rounded-2xl border-[2.5px] border-ink bg-paper p-3 shadow-[3px_3px_0_var(--color-ink)]">
      <div className="flex items-start gap-3">
        <div className="min-w-0 flex-1">
          <span className="font-heading text-sm font-bold text-ink">{s.name}</span>
          {isSection && (
            <span className="ml-1.5 rounded-full border border-ink/25 px-1.5 py-px font-body text-[9px] font-bold uppercase tracking-wide text-muted-ink">
              {t('stores.section.badge')}
            </span>
          )}
          <span className="mt-0.5 block font-body text-[11px] text-muted-ink">
            {/* once a store has sections, it's never itself scheduled, so its
                own worker count / opener / pairing / closing-duties settings
                never actually apply — only the shared hours are still real */}
            {!hasSections && (
              <>
                {workerCount === 1 ? t('stores.workerCount.one', { n: workerCount }) : t('stores.workerCount', { n: workerCount })}
                {' · '}
                {s.requiresOpenerSkill ? t('stores.openerRequired') : t('stores.anyoneCanOpen')}
                {s.pairNewWorkers && ` · ${t('stores.newWorkersPaired')}`}
                {!s.tracksClosingDuties && ` · ${t('stores.noClosingDuties')}`}
              </>
            )}
            {s.openTime && s.closeTime && (
              <>
                {!hasSections && ' · '}
                {to12Hour(s.openTime)}–{to12Hour(s.closeTime)}
                {s.nightStart && `, ${t('stores.nightFrom', { time: to12Hour(s.nightStart) })}`}
              </>
            )}
          </span>
        </div>
        <button onClick={onEdit} className="rounded-full border-2 border-ink bg-cream px-2.5 py-0.5 font-heading text-[11px] font-bold text-ink">
          {t('stores.edit')}
        </button>
      </div>
      {/* one row per setting, opening right under itself — instead of a
          wrapping pile of buttons with every panel stacked at the bottom */}
      <div className="mt-2">
        {/* once a store has sections, it's never itself scheduled again — its
            own "shift needs" would just sit there unused, so say where they live */}
        {hasSections ? (
          <p className="border-t-2 border-ink/10 py-2 font-body text-[11px] text-muted-ink">{t('stores.needsLiveInSections')}</p>
        ) : (
          <SettingRow label={t('stores.shiftNeeds', { n: reqCount })} warn={reqCount === 0} open={showNeeds} onToggle={onToggleNeeds}>
            <RequirementsEditor storeId={s.id} onChange={onRefresh} />
          </SettingRow>
        )}
        {/* hours are the physical location's hours (FOH/BOH open and close
            together) — set once on the main store, not per section */}
        {!isSection && (
          <SettingRow label={t('stores.specialHoursBtn')} open={showHours} onToggle={onToggleHours}>
            <SpecialHoursEditor storeId={s.id} onSaved={onRefresh} />
          </SettingRow>
        )}
        {/* once a store has sections, closing-time roles are each section's
            own thing (FOH vs. BOH close differently) — set them up there */}
        {!hasSections && (
          <SettingRow label={t('stores.responsibilitiesBtn')} open={showResp} onToggle={onToggleResp}>
            <ResponsibilitiesEditor storeId={s.id} />
          </SettingRow>
        )}
        {/* the parent's own sign-up link covers every section (the worker
            picks which one to join), so a section doesn't need its own */}
        {!isSection && (
          <SettingRow label={t('stores.signupLink')} open={showInvite} onToggle={onToggleInvite}>
            <StoreInviteLink storeId={s.id} />
          </SettingRow>
        )}
        {/* when the weekly availability email and next-week auto-draft go
            out — a physical-location setting, like hours */}
        {!isSection && onToggleTiming && onSaveTiming && (
          <SettingRow label={t('stores.timing.button')} open={!!showTiming} onToggle={onToggleTiming}>
            <TimingPanel store={s} onSave={onSaveTiming} />
          </SettingRow>
        )}
        {/* swap approval and cutoff — per physical location, like hours */}
        {!isSection && onToggleTrades && onSaveTrades && (
          <SettingRow label={t('stores.trades.button')} open={showTrades} onToggle={onToggleTrades}>
            <TradesPanel store={s} onSave={onSaveTrades} />
          </SettingRow>
        )}
        {/* off unless a store wants it — plenty clock in on their register */}
        {!isSection && onToggleClock && onSaveClock && (
          <SettingRow label={t('stores.clock.button', { mode: t(`stores.clock.mode.${s.timeClock}`) })} open={showClock} onToggle={onToggleClock}>
            <TimeClockPanel store={s} onSave={onSaveClock} />
          </SettingRow>
        )}
      </div>
      {/* deleting a top-level store is owner-only (bigger, more structural),
          but a section can be removed by whoever manages it — same split as
          adding one. Kept apart from the everyday settings above. */}
      {(isOwner || isSection) && (
        <button
          onClick={onDelete}
          className="mt-1 font-body text-[11px] font-bold text-coral-dark underline-offset-2 hover:underline"
        >
          {t('stores.delete')}
        </button>
      )}
    </div>
  )
}

/** One setting on a store card: its name, and its panel right under it when open. */
function SettingRow({
  label,
  warn,
  open,
  onToggle,
  children,
}: {
  label: string
  /** needs doing before this store can be scheduled */
  warn?: boolean
  open: boolean
  onToggle: () => void
  children: ReactNode
}) {
  return (
    <div className="border-t-2 border-ink/10">
      <button onClick={onToggle} aria-expanded={open} className="flex w-full items-center justify-between gap-2 py-2 text-left">
        <span className={`font-heading text-xs font-bold ${warn ? 'text-coral-dark' : 'text-ink'}`}>{label}</span>
        <span aria-hidden className={`font-heading text-base leading-none text-muted-ink transition-transform ${open ? 'rotate-90' : ''}`}>
          ›
        </span>
      </button>
      {open && <div className="pb-2">{children}</div>}
    </div>
  )
}

const CUTOFF_HOURS = [0, 2, 4, 12, 24, 48]

/** How shift trades work here: whether a coworker taking a shift needs a
 * manager's OK, and how close to a shift trades stop. */
function TradesPanel({ store, onSave }: { store: Store; onSave: (patch: StorePatch) => void }) {
  const t = useT()
  const [autoApproveTrades, setAutoApproveTrades] = useState(store.autoApproveTrades)
  const [tradeCutoffHours, setTradeCutoffHours] = useState(store.tradeCutoffHours)
  return (
    <div className="mt-2 flex flex-col gap-2 rounded-xl border-2 border-ink/15 bg-cream/40 p-2.5">
      <Toggle
        on={autoApproveTrades}
        onClick={() => setAutoApproveTrades((v) => !v)}
        label={t('stores.trades.autoApprove')}
        hint={t('stores.trades.autoApproveHint')}
      />
      <label className="flex flex-wrap items-center gap-1.5 font-body text-[11px] font-bold text-muted-ink">
        {t('stores.trades.cutoff')}
        <select
          value={tradeCutoffHours}
          onChange={(e) => setTradeCutoffHours(Number(e.target.value))}
          className="rounded-lg border-2 border-ink bg-cream px-2 py-1 font-body text-xs text-ink outline-none"
        >
          {/* a value set some other way still shows up as itself */}
          {[...new Set([...CUTOFF_HOURS, store.tradeCutoffHours])].sort((a, b) => a - b).map((h) => (
            <option key={h} value={h}>
              {h === 0 ? t('stores.trades.cutoff.none') : t('stores.trades.cutoff.hours', { n: h })}
            </option>
          ))}
        </select>
      </label>
      <button
        onClick={() => onSave({ name: store.name, autoApproveTrades, tradeCutoffHours })}
        className="self-start rounded-full border-2 border-ink bg-green px-3 py-0.5 font-heading text-[11px] font-bold text-white"
      >
        {t('common.save')}
      </button>
    </div>
  )
}

const CLOCK_MODES: TimeClockMode[] = ['OFF', 'APP', 'POS']

/** Whether — and where — this store tracks hours worked: not at all (Payroll
 * goes by the schedule), clocking in on FruitCrew, or the POS's own clock. */
function TimeClockPanel({ store, onSave }: { store: Store; onSave: (patch: StorePatch) => void }) {
  const t = useT()
  const [mode, setMode] = useState<TimeClockMode>(store.timeClock)
  return (
    <div className="mt-2 flex flex-col gap-2 rounded-xl border-2 border-ink/15 bg-cream/40 p-2.5">
      <div role="radiogroup" aria-label={t('stores.clock.title')} className="flex flex-col gap-1.5">
        {CLOCK_MODES.map((m) => {
          const on = m === mode
          return (
            <button
              key={m}
              role="radio"
              aria-checked={on}
              onClick={() => setMode(m)}
              className={`flex items-start gap-2.5 rounded-xl border-2 px-3 py-2 text-left ${
                on ? 'border-ink bg-paper' : 'border-ink/20 bg-transparent hover:border-ink/50'
              }`}
            >
              <span
                aria-hidden
                className={`mt-0.5 h-3.5 w-3.5 shrink-0 rounded-full border-2 border-ink ${on ? 'bg-green' : 'bg-paper'}`}
              />
              <span className="flex min-w-0 flex-col gap-0.5">
                <span className="font-heading text-xs font-bold text-ink">{t(`stores.clock.opt.${m}`)}</span>
                <span className="font-body text-[10px] text-muted-ink">{t(`stores.clock.opt.${m}.hint`)}</span>
              </span>
            </button>
          )
        })}
      </div>
      <button
        onClick={() => onSave({ name: store.name, timeClock: mode })}
        disabled={mode === store.timeClock}
        className="self-start rounded-full border-2 border-ink bg-green px-3 py-0.5 font-heading text-[11px] font-bold text-white disabled:opacity-40"
      >
        {t('common.save')}
      </button>
    </div>
  )
}

/** When this store emails workers to check next week's availability, and when
 * it auto-drafts next week — its own panel rather than buried in Edit. */
