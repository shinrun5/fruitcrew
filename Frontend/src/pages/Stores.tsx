function EditStore({
  store,
  hasSections = false,
  onSave,
  onCancel,
}: {
  store: Store
  /** true once this store has its own sections — the opener/pairing/closing-
   * duties settings never apply to a store that's never itself scheduled,
   * so don't offer to edit them */
  hasSections?: boolean
  onSave: (patch: StorePatch) => void
  onCancel: () => void
}) {
  const t = useT()
  const [name, setName] = useState(store.name)
  const [requiresOpenerSkill, setRequiresOpenerSkill] = useState(store.requiresOpenerSkill)
  const [pairNewWorkers, setPairNewWorkers] = useState(store.pairNewWorkers)
  const [tracksClosingDuties, setTracksClosingDuties] = useState(store.tracksClosingDuties)

  return (
    <div className="flex flex-col gap-3 rounded-2xl border-[2.5px] border-ink bg-paper p-3 shadow-[3px_3px_0_var(--color-ink)]">
      <input
        value={name}
        onChange={(e) => setName(e.target.value)}
        className="rounded-lg border-2 border-ink bg-cream px-2 py-1 font-body text-sm font-bold text-ink outline-none"
      />
      {!hasSections && (
        <div className="flex flex-wrap gap-x-3 gap-y-1.5">
          <label className={checkboxRow}>
            <input
              type="checkbox"
              checked={requiresOpenerSkill}
              onChange={(e) => setRequiresOpenerSkill(e.target.checked)}
            />
            {t('stores.openerSkillRequiredLabel')}
          </label>
          <label className={checkboxRow}>
            <input
              type="checkbox"
              checked={pairNewWorkers}
              onChange={(e) => setPairNewWorkers(e.target.checked)}
            />
            {t('stores.pairNewWorkersLabel')}
          </label>
          <label className={checkboxRow}>
            <input
              type="checkbox"
              checked={tracksClosingDuties}
              onChange={(e) => setTracksClosingDuties(e.target.checked)}
            />
            {t('stores.tracksClosingDutiesLabel')}
          </label>
        </div>
      )}
      <div className="flex justify-end gap-2 border-t border-ink/10 pt-2.5">
        <button
          onClick={() =>
            name.trim() &&
            onSave({
              name: name.trim(),
              requiresOpenerSkill,
              pairNewWorkers,
              tracksClosingDuties,
            })
          }
          className="rounded-full border-2 border-ink bg-green px-3 py-0.5 font-heading text-[11px] font-bold text-white"
        >
          {t('common.save')}
        </button>
        <button
          onClick={onCancel}
          className="rounded-full border-2 border-ink bg-cream px-3 py-0.5 font-heading text-[11px] font-bold text-ink"
        >
          {t('stores.cancel')}
        </button>
      </div>
    </div>
  )
}
