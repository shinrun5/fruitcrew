const dicts: Record<Lang, Partial<Record<Key, string>>> = { en, zh, es }

function readLang(): Lang {
  // a link from the landing page carries its language (?lang=es), so someone
  // reading the Spanish page lands on a Spanish sign-up / log-in screen
  try {
    const q = new URLSearchParams(window.location.search).get('lang')
    if (q === 'en' || q === 'zh' || q === 'es') {
      try {
        localStorage.setItem(KEY, q)
      } catch {
        /* ignore */
      }
      return q
    }
  } catch {
    /* ignore */
  }
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'en' || v === 'zh' || v === 'es') return v
  } catch {
    /* ignore */
  }
  try {
    const nav = navigator.language?.toLowerCase()
    if (nav?.startsWith('zh')) return 'zh'
    if (nav?.startsWith('es')) return 'es'
  } catch {
    /* ignore */
  }
  return 'en'
}

// so date/day labels are right on the very first paint, before <I18nProvider> renders
setTimeLang(readLang())

interface Ctx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
}
const I18nCtx = createContext<Ctx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)
  // keep the date/day helpers in lib/time in step with the toggle, before children render
  setTimeLang(lang)
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    setTimeLang(l)
    try {
      localStorage.setItem(KEY, l)
    } catch {
      /* ignore */
    }
  }, [])
  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      let s: string = dicts[lang][key] ?? en[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
      return s
    },
    [lang],
  )
  return <I18nCtx value={{ lang, setLang, t }}>{children}</I18nCtx>
}

export function useI18n(): Ctx {
  const c = useContext(I18nCtx)
  if (!c) throw new Error('useI18n must be used within <I18nProvider>')
  return c
}

/** shorthand for components that only need to translate */
export function useT() {
  return useI18n().t
}
